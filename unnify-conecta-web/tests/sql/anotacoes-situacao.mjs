// Situação e arquivamento das anotações (migration 061) — PostgreSQL LOCAL; tudo desfeito no final (ROLLBACK).
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { Client } = require('pg');
const url = process.argv[2] ?? 'postgres://postgres@localhost:55432/unnify_local';
if (!/localhost|127\.0\.0\.1/.test(url)) throw new Error('Recusado: só banco local.');
const c = new Client({ connectionString: url });
await c.connect();
const r = [];
const ok = (n, cond, x = '') => r.push({ n, ok: !!cond, x });
const um = async (s, p = []) => (await c.query(s, p)).rows[0];
const como = (id) => c.query("select set_config('request.jwt.claims', $1, false), set_config('request.jwt.claim.sub', $2, false), set_config('role', 'authenticated', false)", [JSON.stringify({ sub: id, role: 'authenticated' }), id]);
const admin = () => c.query("reset role; select set_config('request.jwt.claims', '', false), set_config('request.jwt.claim.sub', '', false)");
async function falha(n, s, p, t) { await c.query('savepoint t'); try { await c.query(s, p); await c.query('release savepoint t'); ok(n, false, 'não falhou'); } catch (e) { await c.query('rollback to savepoint t'); ok(n, !t || e.message.includes(t), e.message.slice(0, 110)); } }

await c.query('begin');
await admin();
const [donoA, donoB] = (await c.query("select id_usuario from perfis where funcao_global='user' and tipo_usuario='empresa' limit 2")).rows.map((x) => x.id_usuario);
const A = (await um("insert into empresas (cnpj, razao_social, email_comercial, cidade, estado, tipo_empresa, status_registro, criado_por) values ('61.616.000/0001-61','Anot 61','a@local.test','Palmas','TO','comum','ATIVA',$1) returning id", [donoA])).id;
await c.query("insert into usuarios_empresas (id_usuario, id_empresa, tipo_vinculacao, ativo) values ($1,$2,'dono',true)", [donoA, A]);
await como(donoA);
const SALVAR = 'select salvar_anotacao($1,$2,$3,$4,$5,$6::text[]) id';
const id = (await um(SALVAR, [null, A, 'Sistema de Pontos', 'Ideia do portal', 'ideias', []])).id;
const sit = async () => (await um('select situacao, arquivada_em is not null arq, fixada from anotacoes where id=$1', [id]));
const ALT = 'select alterar_situacao_anotacao($1,$2)';
ok('Nova anotação começa pendente e não arquivada', (await sit()).situacao === 'pendente' && !(await sit()).arq);
await c.query(ALT, [id, 'em_andamento']);
ok('Iniciar: em andamento', (await sit()).situacao === 'em_andamento');
await falha('Não inicia de novo', ALT, [id, 'em_andamento'], 'pendente');
await c.query(ALT, [id, 'concluida']);
ok('Concluir', (await sit()).situacao === 'concluida');
await falha('Encerrada não é cancelada sem reabrir', ALT, [id, 'cancelada'], 'reabra');
await c.query(ALT, [id, 'pendente']);
await c.query(ALT, [id, 'cancelada']);
ok('Reabrir e cancelar', (await sit()).situacao === 'cancelada');
await falha('Situação inválida recusada', ALT, [id, 'apagada'], 'inválida');
await c.query('select alternar_fixacao_anotacao($1,true)', [id]);
await c.query('select arquivar_anotacao($1,true)', [id]);
ok('Arquivar (e desafixa)', (await sit()).arq && !(await sit()).fixada);
await falha('Arquivada não é editada', SALVAR, [id, A, 'Outro título', 'x', 'ideias', []], 'desarquive');
await falha('Arquivada não muda de situação', ALT, [id, 'pendente'], 'desarquive');
await falha('Arquivada não é fixada', 'select alternar_fixacao_anotacao($1,true)', [id], 'desarquive');
await c.query('select arquivar_anotacao($1,false)', [id]);
await c.query(SALVAR, [id, A, 'Sistema de Pontos v2', 'Ideia do portal', 'ideias', []]);
ok('Desarquivar libera a edição', !(await sit()).arq && (await um('select titulo from anotacoes where id=$1', [id])).titulo === 'Sistema de Pontos v2');
await c.query('select arquivar_anotacao($1,true)', [id]);
await c.query('select excluir_anotacao($1)', [id]);
await admin();
ok('Arquivada ainda pode ser excluída', (await um('select excluido_em is not null e from anotacoes where id=$1', [id])).e);
await como(donoA);
const pessoal = (await um(SALVAR, [null, A, 'Lembrete pessoal', 'x', 'pessoal', []])).id;
await como(donoB);
await falha('Outra empresa não altera', ALT, [pessoal, 'concluida'], 'não encontrada');
await falha('Outra empresa não arquiva', 'select arquivar_anotacao($1,true)', [pessoal], 'não encontrada');
await admin();
await c.query('set role anon');
await falha('Anônimo não executa', ALT, [pessoal, 'concluida'], 'permission denied');

await c.query('rollback');
await c.end();
const falhas = r.filter((x) => !x.ok);
for (const x of r) console.log(`${x.ok ? '✅' : '❌'} ${x.n}${x.ok ? '' : ` — ${x.x}`}`);
console.log(`\n${r.length - falhas.length}/${r.length} verificações OK`);
process.exit(falhas.length ? 1 : 0);
